/**
 * Зафиксированный глиф бренда — строгая T + рукописный плюс-росчерк (айдентика
 * «Пометка учителя», дизайн-система v2 §10, слайс #73 спеки #68).
 *
 * Пути ПЕРЕНЕСЕНЫ КАК ДАННЫЕ из канона v4.1 (`kit.jsx` → `PLUS_GLYPHS`, `CHECK_PATH`,
 * `T_RECTS`) — не перерисовывать и не округлять: знак один, и он уже утверждён.
 *
 * Длины путей — КОНСТАНТЫ, посчитанные заранее по самой геометрии (`getTotalLength()`
 * в браузере, viewBox 0 0 100 100). Мерить их в рантайме нельзя: у react-native-svg на
 * iOS открытый баг — на первом кадре длина ещё 0, и анимация просто не стартует
 * (issue #2200, резолюшн #67 вопрос 1).
 */

/** Один росчерк: путь + его длина в единицах viewBox. */
export interface StrokeGeometry {
  d: string;
  length: number;
}

/** Оптические размеры глифа: перо (display) · маркер (UI) · микро (почти прямой). */
export interface PlusGlyph {
  /** Толщина линии в единицах viewBox — у каждого размера своя, это часть знака. */
  sw: number;
  /** Вертикаль плюса — рисуется первой. */
  v: StrokeGeometry;
  /** Горизонталь плюса — рисуется следом. */
  h: StrokeGeometry;
}

